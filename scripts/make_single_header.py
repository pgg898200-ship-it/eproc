#!/usr/bin/env python3
"""Bundle eproc's C11 headers and sources into a single-header dist/eproc_single.h.

Usage in C/C++ projects (stb-style):
    #define EPROC_IMPLEMENTATION
    #include "eproc_single.h"
"""
from __future__ import annotations

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CSRC = ROOT / "csrc"
DIST = ROOT / "dist"

SOURCES = [
    "eproc_eprocess.c",
    "eproc_conformal.c",
    "eproc_fusion.c",
    "eproc_subsample.c",
]

LOCAL_INCLUDE_RE = re.compile(r'^\s*#include\s+"eproc(?:_seqlock|_internal)?\.h"\s*$')


def strip_local_includes(text: str) -> str:
    return "\n".join(
        line for line in text.splitlines() if not LOCAL_INCLUDE_RE.match(line)
    )


def build_single_header() -> Path:
    DIST.mkdir(parents=True, exist_ok=True)
    out_path = DIST / "eproc_single.h"

    header = (CSRC / "eproc.h").read_text(encoding="utf-8")
    seqlock = (CSRC / "eproc_seqlock.h").read_text(encoding="utf-8")
    internal_path = CSRC / "eproc_internal.h"
    internal = strip_local_includes(internal_path.read_text(encoding="utf-8")) if internal_path.exists() else ""

    parts = [
        "/*\n"
        " * eproc_single.h — Single-header C11 distribution of eproc\n"
        " * Generated by scripts/make_single_header.py\n"
        " * License: Apache-2.0\n"
        " *\n"
        " * In exactly ONE C/C++ translation unit, define:\n"
        " *   #define EPROC_IMPLEMENTATION\n"
        " *   #include \"eproc_single.h\"\n"
        " * Compile with: -std=c11 -O3 -ffp-contract=off -lm (-mavx2 -mfma optional)\n"
        " */\n",
        header.strip(),
        "\n#ifdef EPROC_IMPLEMENTATION\n",
        "#ifndef EPROC_IMPLEMENTATION_INCLUDED\n",
        "#define EPROC_IMPLEMENTATION_INCLUDED\n\n",
        seqlock.strip(),
        "\n",
        internal.strip(),
        "\n",
    ]

    for name in SOURCES:
        src_path = CSRC / name
        if not src_path.exists():
            raise FileNotFoundError(f"Missing source file: {src_path}")
        body = strip_local_includes(src_path.read_text(encoding="utf-8"))
        parts.append(f"\n/* ==================== {name} ==================== */\n")
        parts.append(body.strip())
        parts.append("\n")

    parts.append("\n#endif /* EPROC_IMPLEMENTATION_INCLUDED */\n")
    parts.append("#endif /* EPROC_IMPLEMENTATION */\n")

    out_path.write_text("\n".join(parts), encoding="utf-8")
    return out_path


if __name__ == "__main__":
    path = build_single_header()
    print(f"Wrote {path} ({path.stat().st_size:,} bytes)")
